test('historical analysis requires selection and consent, and preserves the original response',async({page})=>{
 await page.route('**/api/session',async route=>{const response=await route.fetch();await route.fulfill({json:{...await response.json(),chatgpt:true}});});
 await page.goto('/');await expect(page.getByRole('button',{name:'Open Vocabulary',exact:true})).toBeEnabled();
 const s=await(await page.request.get('/api/session')).json();const headers={origin:'http://127.0.0.1:4181','x-csrf-token':s.csrf};
 const answer='I support another trial because access matters. [progress-history-check]';
 const id=crypto.randomUUID();await page.request.post('/api/attempts',{headers,data:{id,activityId:'writing-5-2',answer,source:'typed',assisted:false,mode:'practice'}});
 await page.goto('/?view=progress');await page.getByRole('button',{name:'View history',exact:true}).click();
 const row=page.locator('.history-record').filter({has:page.getByLabel('Select response '+id,{exact:true})});
 await page.getByLabel('Select response '+id,{exact:true}).check();
 await expect(page.getByRole('button',{name:'Assess 1 response',exact:true})).toBeDisabled();
 await page.getByRole('checkbox',{name:/I have disabled app credit use in ChatGPT settings. Use my included allowance to assess/}).check();
 await page.getByRole('button',{name:'Assess 1 response',exact:true}).click();
 await expect(page.getByText('1 response assessed. Original feedback is unchanged.',{exact:true})).toBeVisible();
 const updated=page.locator('.history-record').filter({hasText:'Write an Email'}).filter({hasText:'Tutor observations'}).first();
 await expect(updated).toBeVisible();
 const events=await(await page.request.get('/api/progress')).json();expect(events.events.find((e:any)=>e.id===id).data.answer).toBe(answer);
 const backup=await(await page.request.get('/api/backup')).json();expect(backup.assessments.some((a:any)=>a.attemptId===id&&a.observations.length===5)).toBe(true);
});
