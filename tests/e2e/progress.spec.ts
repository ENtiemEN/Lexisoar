 await expect(page.getByRole('heading',{name:'Your four skills',exact:true})).toBeVisible();
 await expect(page.getByRole('heading',{name:'Your learning evidence',exact:true})).toBeVisible();
 await expect(page.getByRole('heading',{name:'Patterns to work on',exact:true})).toBeVisible();
 await expect(page.getByRole('heading',{name:'Remember & revisit',exact:true})).toBeVisible();
 await expect(page.getByRole('heading',{name:'Your history',exact:true})).toHaveCount(0);
 await expect(page.getByText('Effort points',{exact:true})).toHaveCount(0);
